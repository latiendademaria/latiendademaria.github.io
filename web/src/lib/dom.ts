/** Escapa texto para interpolarlo en HTML */
export function esc(v: unknown): string {
  return String(v ?? '').replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

export const $ = <T extends Element = HTMLElement>(sel: string, root: ParentNode = document) =>
  root.querySelector(sel) as T;
export const $$ = <T extends Element = HTMLElement>(sel: string, root: ParentNode = document) =>
  Array.from(root.querySelectorAll(sel)) as T[];

let toastTimer: number | undefined;
export function toast(msg: string, kind: 'ok' | 'error' = 'ok') {
  let el = document.getElementById('toast');
  if (!el) {
    el = document.createElement('div');
    el.id = 'toast';
    el.setAttribute('role', 'status');
    document.body.append(el);
  }
  el.className = `toast is-on${kind === 'error' ? ' toast--error' : ''}`;
  el.textContent = msg;
  clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => el!.classList.remove('is-on'), 3200);
}

/** Bloquea el scroll del body mientras hay un panel abierto */
export function lockScroll(on: boolean) {
  document.documentElement.style.overflow = on ? 'hidden' : '';
}

